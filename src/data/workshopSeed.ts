export function calculateJobTotals(job: JobCard) {
  const breakdown = computeRepairOrderTotals(job);
  return {
    laborSubtotal: breakdown.laborSubtotal,
    partsSubtotal: breakdown.partsSubtotal,
    subtotal: breakdown.laborSubtotal + breakdown.partsSubtotal,
    cgstAmount: breakdown.cgstAmount,
    sgstAmount: breakdown.sgstAmount,
    taxAmount: breakdown.taxAmount,
    grandTotal: breakdown.grandTotal,
    balanceDue: breakdown.balanceDue,
  };
}
